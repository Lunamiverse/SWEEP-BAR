"""Generates Source/FontData.cpp/.h from Resources/fonts/*.ttf (SIL OFL fonts embedded in the plugin)."""
import pathlib

here = pathlib.Path(__file__).resolve().parent
fonts = sorted((here / "fonts").glob("*.ttf"))
src = here.parent / "Source"

h = ["// Generated by Resources/embed_fonts.py. Barlow fonts, SIL Open Font License (Resources/fonts/OFL.txt).",
     "#pragma once", "#include <cstddef>", "", "namespace fontdata", "{"]
c = ['// Generated by Resources/embed_fonts.py. Do not edit.', '#include "FontData.h"', "", "namespace fontdata", "{"]
for f in fonts:
    name = f.stem.replace("-", "_")
    data = f.read_bytes()
    h.append(f"    extern const unsigned char {name}[];")
    h.append(f"    constexpr std::size_t {name}Size = {len(data)};")
    rows = []
    for i in range(0, len(data), 24):
        rows.append("        " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    c.append(f"    const unsigned char {name}[] = {{")
    c.extend(rows)
    c.append("    };")
h.append("}")
c.append("}")
(src / "FontData.h").write_text("\n".join(h) + "\n")
(src / "FontData.cpp").write_text("\n".join(c) + "\n")
print("embedded", [f.name for f in fonts])
